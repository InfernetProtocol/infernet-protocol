"""CfC vs GRU (vs LTC research, vs a script baseline) on identical synthetic splits."""

import json
import statistics
from pathlib import Path

from .data import encode_episode, split_episodes, verify_bundle
from .evaluate import evaluate_encoded, evaluate_markov
from .export import runtime_ref
from .synth import make_bundle
from .train import DEFAULTS, train

KEYS = ["action_accuracy", "target_accuracy", "step_accuracy", "episode_success", "external_write_recall", "latency_ms_p50", "latency_ms_p95"]


def run(out_dir, per_task=160, families=("cfc", "gru", "ltc"), seeds=(0, 1, 2), epochs=None, shift_per_task=40, on_event=None, threads=4):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    main = make_bundle(per_task=per_task, seed=7)
    shift = make_bundle(per_task=shift_per_task, seed=11, shifted=True)
    verify_bundle(main)
    verify_bundle(shift)
    (out / "bench-bundle.json").write_text(json.dumps(main, separators=(",", ":")), "utf-8")
    (out / "bench-shift-bundle.json").write_text(json.dumps(shift, separators=(",", ":")), "utf-8")
    splits = split_episodes(main)
    held = {}
    for e in splits["test"]:
        held[e["task"]] = held.get(e["task"], 0) + 1
    results = {}
    hp_base = dict(DEFAULTS)
    if epochs:
        hp_base["epochs"] = epochs
    for fam in families:
        runs = []
        for seed in seeds:
            hp = {**hp_base, "seed": seed}
            model, info = train(main, fam, hp, "cpu", threads, on_event)
            test = evaluate_encoded(model, info["encoded"]["test"])
            enc_shift = [encode_episode(e, hp["feature_dim"]) for e in shift["episodes"]]
            sh = evaluate_encoded(model, enc_shift, timing=False)
            runs.append({"seed": seed, "train_seconds": info["train_seconds"], "epochs_run": info["epochs_run"], "params": model.param_count(), "test": test, "shift": sh})
            if on_event:
                on_event({"event": "bench_run", "family": fam, "seed": seed, "step_accuracy": test["step_accuracy"], "episode_success": test["episode_success"], "shift_episode_success": sh["episode_success"]})
        results[fam] = runs
    markov_test = evaluate_markov(splits["train"], splits["test"])
    markov_shift = evaluate_markov(splits["train"], shift["episodes"])
    summary = {
        "runtime": runtime_ref(),
        "dataset_hash": main["manifest"]["dataset_hash"],
        "shift_dataset_hash": shift["manifest"]["dataset_hash"],
        "split_counts": main["manifest"]["splits"]["counts"],
        "held_out_per_task": held,
        "shift_episodes": len(shift["episodes"]),
        "hyperparameters": hp_base,
        "seeds": list(seeds),
        "families": {},
        "script_baseline": {"test": markov_test, "shift": markov_shift},
    }
    for fam, runs in results.items():
        agg = {}
        for k in KEYS:
            vals = [r["test"].get(k, 0.0) for r in runs]
            agg[k] = {"mean": round(statistics.mean(vals), 4), "min": round(min(vals), 4), "max": round(max(vals), 4)}
        agg["shift_episode_success"] = {"mean": round(statistics.mean(r["shift"]["episode_success"] for r in runs), 4)}
        agg["shift_step_accuracy"] = {"mean": round(statistics.mean(r["shift"]["step_accuracy"] for r in runs), 4)}
        agg["train_seconds"] = {"mean": round(statistics.mean(r["train_seconds"] for r in runs), 2)}
        agg["params"] = runs[0]["params"]
        agg["by_task_episode_success"] = {
            t: round(statistics.mean(r["test"]["by_task"][t]["episode_success"] for r in runs), 4) for t in runs[0]["test"]["by_task"]
        }
        summary["families"][fam] = {"aggregate": agg, "runs": runs}
    (out / "benchmark.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", "utf-8")
    return summary


def render_markdown(s):
    fams = list(s["families"])
    lines = [
        "# Temporal policy benchmark: CfC vs GRU",
        "",
        "Generated by `python -m infernet_liquid bench` on synthetic mock desktop traces",
        f"(runtime {s['runtime']['name']} {s['runtime']['version']}, torch {s['runtime']['torch']}, ncps {s['runtime']['ncps']}, CPU).",
        "",
        f"- Dataset `{s['dataset_hash']}`: splits {s['split_counts']}, split by recording session.",
        f"- Held-out test episodes per workflow: {s['held_out_per_task']}.",
        f"- Layout-shift holdout: {s['shift_episodes']} episodes on an unseen layout (renamed controls, reordered) `{s['shift_dataset_hash']}`.",
        f"- Same splits, features, hidden size ({s['hyperparameters']['hidden_units']}), optimiser and epoch budget for every family; seeds {s['seeds']}; mean (min to max) over seeds.",
        "",
        "Predeclared metric: **episode_success** on held-out test episodes (every step's action type and target right under teacher forcing).",
        "Secondary: step_accuracy, layout-shift episode success, external_write_recall (an external write predicted as one, so approval gating fires), batch-1 step latency.",
        "",
        "| model | params | episode success | step acc | target acc | ext-write recall | shift episode success | latency p50 / p95 ms | train s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for f in fams:
        a = s["families"][f]["aggregate"]
        r = lambda k: f"{a[k]['mean']:.3f} ({a[k]['min']:.3f} to {a[k]['max']:.3f})"
        label = f + (" (research)" if f == "ltc" else " (baseline)" if f == "gru" else "")
        lines.append(f"| {label} | {a['params']} | {r('episode_success')} | {r('step_accuracy')} | {a['target_accuracy']['mean']:.3f} | {a['external_write_recall']['mean']:.3f} | {a['shift_episode_success']['mean']:.3f} | {a['latency_ms_p50']['mean']:.3f} / {a['latency_ms_p95']['mean']:.3f} | {a['train_seconds']['mean']:.1f} |")
    m = s["script_baseline"]
    lines.append(f"| script (majority next action) | 0 | {m['test']['episode_success']:.3f} | {m['test']['step_accuracy']:.3f} | {m['test']['target_accuracy']:.3f} | {m['test']['external_write_recall']:.3f} | {m['shift']['episode_success']:.3f} | n/a | 0 |")
    lines += ["", "Per-workflow episode success (mean over seeds):", "", "| model | " + " | ".join(s["families"][fams[0]]["aggregate"]["by_task_episode_success"]) + " |", "|---|" + "---|" * len(s["families"][fams[0]]["aggregate"]["by_task_episode_success"])]
    for f in fams:
        bt = s["families"][f]["aggregate"]["by_task_episode_success"]
        lines.append(f"| {f} | " + " | ".join(f"{v:.3f}" for v in bt.values()) + " |")
    if "cfc" in s["families"] and "gru" in s["families"]:
        c = s["families"]["cfc"]["aggregate"]
        g = s["families"]["gru"]["aggregate"]
        d = c["episode_success"]["mean"] - g["episode_success"]["mean"]
        if c["episode_success"]["min"] > g["episode_success"]["max"]:
            verdict = "CfC beats GRU on every seed: CfC may be selected for these tasks."
        elif g["episode_success"]["min"] > c["episode_success"]["max"]:
            verdict = "GRU beats CfC on every seed: keep GRU."
        else:
            verdict = "Neither beats the other on every seed: keep GRU (cheaper, simpler)."
        lines += [
            "",
            "## Verdict",
            "",
            f"{verdict} CfC minus GRU mean episode success: {d:+.3f}.",
            "Rule (pipeline PRD): a liquid model is chosen only when it beats the baseline on the predeclared metric on every seed.",
            "",
            "Limits: synthetic traces from a generator with three layouts. They exercise the pipeline and the comparison method; they say nothing about real desktops. Rerun on reviewed W3BS episodes before choosing a family for a real task.",
        ]
    return "\n".join(lines) + "\n"
